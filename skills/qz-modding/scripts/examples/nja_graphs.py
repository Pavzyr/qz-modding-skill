"""Paste texts (Ctrl+V into a Blueprint graph) for NoJacketsAuto (2026-10-20): jackets (TorsoTop) of checkpoint visitors are
hidden while a real top (Torso) is under them; no toggle.
  python -I nja_graphs.py <out_dir>
  1_BP_NJA_Manager__EventGraph.txt -> BP_NJA_Manager, Event Graph
  2_ABP_NJA_DocPost__EventGraph.txt -> ABP_NJA_DocPost, Event Graph
  3_ABP_NJA_DocPost__AnimGraph.txt  -> ABP_NJA_DocPost, AnimGraph (then drag "Input Pose" -> "Output Pose")
Differences from the instruction (same behaviour): everything is in the Event Graph (no functions NJA_ApplyAll/ApplyOne -
calling own events/functions from a pasted graph breaks, notes 2026-10-19); Jacket/Top are manager variables, not locals;
tags are added/removed in place on the ComponentTags getter (no extra Set Component Tags).
Timer 0.25 s -> all QzNPCCharacter -> components by class SkeletalMeshComponent -> name TorsoTop = Jacket, Torso = Top ->
ShouldHide = real Top AND real Jacket (mesh set and not SKM_Root_Template) -> hide + tag NJA_Hidden / show back only if tagged.
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, ".."))
import graph_helpers as cg
from graph_helpers import CB, P, C, K2, T_BOOL, T_STR, WCO, KSL, KML
from qz_bp_paste import Graph, mkpin

MOD = "/NoJacketsAuto"
BPGC = "/Script/Engine.BlueprintGeneratedClass"
MGR_C = "%s'%s/BP_NJA_Manager.BP_NJA_Manager_C'" % (BPGC, MOD)
ABP_C = "/Script/Engine.AnimBlueprintGeneratedClass'%s/Carrier/ABP_NJA_DocPost.ABP_NJA_DocPost_C'" % MOD
KSYS, KAL = "/Script/Engine.KismetSystemLibrary", "/Script/Engine.KismetArrayLibrary"
SKMC = C("/Script/Engine.SkeletalMeshComponent")
T_SKMC = ("object", "", SKMC, "None")
T_SKMCS = ("object", "", SKMC, "Array")
T_NAME = ("name", "", None, "None")
T_NAMES = ("name", "", None, "Array")
T_OBJ = ("object", "", C("/Script/CoreUObject.Object"), "None")
TAG = "NJA_Hidden"


def obj_name(b, x, y):
    return b.pure_static(KSYS, "GetObjectName", [P("Object", "in", T_OBJ, const=True), P("ReturnValue", "out", T_STR)], x, y)


def str_eq(b, s, x, y):
    return b.pure_static(KSL, "EqualEqual_StrStr", [P("A", "in", T_STR), P("B", "in", T_STR, default=s),
                                                    P("ReturnValue", "out", T_BOOL, default="false")], x, y)


def b_and(b, x, y):
    return b.pure_static(KML, "BooleanAND", [P("A", "in", T_BOOL, default="false"), P("B", "in", T_BOOL, default="false"),
                                             P("ReturnValue", "out", T_BOOL, default="false")], x, y)


def b_not(b, x, y):
    return b.pure_static(KML, "Not_PreBool", [P("A", "in", T_BOOL, default="false"), P("ReturnValue", "out", T_BOOL, default="false")], x, y)


def real_mesh(b, comp_get, comp_pin, x, y):
    """(comp -> GetSkeletalMeshAsset) is valid AND its name != SKM_Root_Template  -> returns the AND node."""
    L = b.g.link
    gm = b.call("/Script/Engine.SkeletalMeshComponent", "GetSkeletalMeshAsset",
                [P("ReturnValue", "out", ("object", "", C("/Script/Engine.SkeletalMesh"), "None"))], x, y, pure=True)
    L(comp_get, comp_pin, gm, "self")
    iv = b.is_valid(x + 300, y)
    L(gm, "ReturnValue", iv, "Object")
    on = obj_name(b, x + 300, y + 120)
    L(gm, "ReturnValue", on, "Object")
    eq = str_eq(b, "SKM_Root_Template", x + 550, y + 120)
    L(on, "ReturnValue", eq, "A")
    nt = b_not(b, x + 800, y + 120)
    L(eq, "ReturnValue", nt, "A")
    an = b_and(b, x + 1000, y)
    L(iv, "ReturnValue", an, "A"); L(nt, "ReturnValue", an, "B")
    return an


def has_tag(b, x, y):
    return b.call("/Script/Engine.ActorComponent", "ComponentHasTag",
                  [P("Tag", "in", T_NAME, default=TAG), P("ReturnValue", "out", T_BOOL, default="false")], x, y, pure=True)


def set_vis(b, visible, x, y):
    n = b.call("/Script/Engine.SceneComponent", "SetVisibility",
               [P("bNewVisibility", "in", T_BOOL, default="true" if visible else "false"),
                P("bPropagateToChildren", "in", T_BOOL, default="false")], x, y)
    # a value different from the function's own default is reset by paste unless AutogeneratedDefaultValue is present (notes 2026-10-16)
    for p in n.pins:
        p["body"] = re.sub(r'(DefaultValue="(?:true|false)",)', r'\1AutogeneratedDefaultValue="false",', p["body"])
    return n


def tags_get(b, x, y):
    return b.member("/Script/CoreUObject.Class'/Script/Engine.ActorComponent'", ("object", "", C("/Script/Engine.ActorComponent"), "None"),
                    "ComponentTags", T_NAMES, x, y)


def array_call(b, func, item_pin, ret, x, y):
    return b.g.raw(K2 + "K2Node_CallArrayFunction", ['FunctionReference=(MemberParent="%s",MemberName="%s")' % (C(KAL), func)],
                   [P("execute"), P("then", "out"),
                    P("self", "in", ("object", "", C(KAL), "None"), default_obj="/Script/Engine.Default__KismetArrayLibrary", hidden=True,
                      friendly='NSLOCTEXT("K2Node", "Target", "Target")'),
                    P("TargetArray", "in", T_NAMES, ref=True),
                    P(item_pin, "in", T_NAME, default=TAG, ref=True, const=True),
                    ret], x, y)


def manager():
    b = CB(MGR_C)
    g, L = b.g, b.g.link
    ev = b.event("/Script/Engine.Actor", "ReceiveBeginPlay", 0, 0)
    tm = b.timer(0.25, True, 300, 0)
    ce = b.custom_event("NJA_Update", 0, 300)
    L(ev, "then", tm, "execute"); L(ce, "OutputDelegate", tm, "Delegate")
    # all visitors
    gaa = b.gs("GetAllActorsOfClass", [WCO(), P("ActorClass", "in", ("class", "", C("/Script/Engine.Actor"), "None"), default_obj="/Script/QZSim.QzNPCCharacter"),
                                       P("OutActors", "out", ("object", "", C("/Script/QZSim.QzNPCCharacter"), "Array"))], 300, 300)
    L(ce, "then", gaa, "execute")
    lp1 = g.node("Macro:ForEachLoop", x=650, y=300)
    for pn in ("Array", "Array Element"):
        lp1.pin(pn)["body"] = lp1.pin(pn)["body"].replace(C("/Script/Engine.SceneComponent"), C("/Script/QZSim.QzNPCCharacter"))
    L(gaa, "then", lp1, "Exec"); L(gaa, "OutActors", lp1, "Array")
    # reset Jacket / Top
    sj0 = b.set("Jacket", T_SKMC, 1000, 300)
    st0 = b.set("Top", T_SKMC, 1250, 300)
    L(lp1, "LoopBody", sj0, "execute"); L(sj0, "then", st0, "execute")
    # skeletal mesh components of this visitor
    gcc = b.call("/Script/Engine.Actor", "K2_GetComponentsByClass",
                 [P("ComponentClass", "in", ("class", "", C("/Script/Engine.ActorComponent"), "None"), default_obj="/Script/Engine.SkeletalMeshComponent"),
                  P("ReturnValue", "out", T_SKMCS)], 1250, 550, pure=True)
    L(lp1, "Array Element", gcc, "self")
    lp2 = g.node("Macro:ForEachLoop", x=1550, y=300)
    for pn in ("Array", "Array Element"):
        lp2.pin(pn)["body"] = lp2.pin(pn)["body"].replace(C("/Script/Engine.SceneComponent"), SKMC)
    L(st0, "then", lp2, "Exec"); L(gcc, "ReturnValue", lp2, "Array")
    on = obj_name(b, 1850, 550)
    L(lp2, "Array Element", on, "Object")
    eqj = str_eq(b, "TorsoTop", 2100, 500)
    eqt = str_eq(b, "Torso", 2100, 650)
    L(on, "ReturnValue", eqj, "A"); L(on, "ReturnValue", eqt, "A")
    bra = b.branch(2350, 300)
    L(lp2, "LoopBody", bra, "execute"); L(eqj, "ReturnValue", bra, "Condition")
    sj = b.set("Jacket", T_SKMC, 2650, 250)
    L(bra, "then", sj, "execute"); L(lp2, "Array Element", sj, "Jacket")
    brb = b.branch(2650, 450)
    L(bra, "else", brb, "execute"); L(eqt, "ReturnValue", brb, "Condition")
    st = b.set("Top", T_SKMC, 2900, 450)
    L(brb, "then", st, "execute"); L(lp2, "Array Element", st, "Top")
    # after the component loop: decide
    y = 1000
    gj = b.get("Jacket", T_SKMC, 1550, y)
    gt = b.get("Top", T_SKMC, 1550, y + 450)
    ivj = b.is_valid(1850, y - 150)
    L(gj, "Jacket", ivj, "Object")
    brj = b.branch(2100, y - 250)
    L(lp2, "Completed", brj, "execute"); L(ivj, "ReturnValue", brj, "Condition")
    jreal = real_mesh(b, gj, "Jacket", 1850, y)
    ivt = b.is_valid(1850, y + 300)
    L(gt, "Top", ivt, "Object")
    treal = real_mesh(b, gt, "Top", 1850, y + 450)
    htop = b_and(b, 3100, y + 350)
    L(ivt, "ReturnValue", htop, "A"); L(treal, "ReturnValue", htop, "B")
    hide = b_and(b, 3300, y + 100)
    L(htop, "ReturnValue", hide, "A"); L(jreal, "ReturnValue", hide, "B")
    brs = b.branch(3550, y - 250)
    L(brj, "then", brs, "execute"); L(hide, "ReturnValue", brs, "Condition")
    tg = has_tag(b, 3550, y - 450)
    L(gj, "Jacket", tg, "self")
    # hide: not tagged yet -> invisible + tag
    brh = b.branch(3850, y - 400)
    L(brs, "then", brh, "execute"); L(tg, "ReturnValue", brh, "Condition")
    sv0 = set_vis(b, False, 4150, y - 400)
    L(brh, "else", sv0, "execute"); L(gj, "Jacket", sv0, "self")
    tga = tags_get(b, 4150, y - 600)
    L(gj, "Jacket", tga, "self")
    add = array_call(b, "Array_Add", "NewItem", P("ReturnValue", "out", ("int", "", None, "None"), default="0"), 4450, y - 400)
    L(sv0, "then", add, "execute"); L(tga, "ComponentTags", add, "TargetArray")
    # show: tagged by us -> visible + untag
    brr = b.branch(3850, y - 100)
    L(brs, "else", brr, "execute"); L(tg, "ReturnValue", brr, "Condition")
    sv1 = set_vis(b, True, 4150, y - 100)
    L(brr, "then", sv1, "execute"); L(gj, "Jacket", sv1, "self")
    tgr = tags_get(b, 4150, y + 100)
    L(gj, "Jacket", tgr, "self")
    rem = array_call(b, "Array_RemoveItem", "Item", P("ReturnValue", "out", T_BOOL, default="false"), 4450, y - 100)
    L(sv1, "then", rem, "execute"); L(tgr, "ComponentTags", rem, "TargetArray")
    return b.text()


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "."
