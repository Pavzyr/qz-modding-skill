"""Compose pasteable Blueprint graph text (Ctrl+V in the graph editor) from REAL nodes harvested by qz_node_harvest.py.

Plain Python (no engine). Library: %LOCALAPPDATA%/QZSim/Saved/ModSchema/nodes/node_library.json

    from qz_bp_paste import Graph
    g = Graph()
    a = g.node("Event:ReceiveBeginPlay", x=0, y=0)
    b = g.node("CallFunction:K2_SetTimer", x=300, y=0, defaults={"FunctionName": "VT_Update", "Time": "0.1", "bLooping": "true"})
    g.link(a, "then", b, "execute")
    open("out.txt", "w", encoding="utf-8").write(g.text())

Rules (learned from the format):
- every pin keeps its real name/type from the template; PinIds and NodeGuid are regenerated; old LinkedTo are dropped;
- links are written on BOTH pins ("LinkedTo=(NodeName PinId,)");
- header edits (cast target, variable name, event name, enum, ...) are regex replacements on the header lines;
- pins can be dropped (e.g. an unrelated extra pin) or retyped by text replacement.
"""
import json, os, re, uuid

LIB_PATH = os.path.join(os.environ.get("LOCALAPPDATA", ""), "QZSim", "Saved", "ModSchema", "nodes", "node_library.json")
PIN_RE = re.compile(r"^(\s*)CustomProperties Pin \((.*)\)\s*$")


def gid():
    return uuid.uuid4().hex.upper()


def retype(body, category, sub_object=None, container="None", sub_category=""):
    """Rewrite a pin body's PinType: category in exec/bool/int/real/text/string/name/object/class/struct/byte."""
    body = re.sub(r'PinType\.PinCategory="[^"]*"', 'PinType.PinCategory="%s"' % category, body)
    body = re.sub(r'PinType\.PinSubCategory="[^"]*"', 'PinType.PinSubCategory="%s"' % sub_category, body)
    so = 'None' if not sub_object else '"%s"' % sub_object
    body = re.sub(r'PinType\.PinSubCategoryObject=(?:None|"[^"]*")', "PinType.PinSubCategoryObject=" + so, body)
    body = re.sub(r"PinType\.ContainerType=\w+", "PinType.ContainerType=" + container, body)
    body = re.sub(r'DefaultValue="(?:[^"\\]|\\.)*",', "", body)
    body = re.sub(r"DefaultObject=(?:None|\"[^\"]*\"),", "", body)
    body = re.sub(r'AutogeneratedDefaultValue="(?:[^"\\]|\\.)*",', "", body)
    return body


def cls_path(script_or_bp):
    """'/Script/UMG.TextBlock' -> class object path string used in PinSubCategoryObject."""
    if script_or_bp.startswith("/Script/"):
        return "/Script/CoreUObject.Class'%s'" % script_or_bp
    return script_or_bp


def mkpin(name, direction="in", cat="exec", sub="", obj=None, container="None", default=None, default_obj=None,
          hidden=False, friendly=None, member_ref="()", ref=False, const=False, not_connectable=False):
    """Pin body in the exact field order of UE copy text (PinId is added by Graph.raw)."""
    s = 'PinName="%s",' % name
    if friendly:
        s += "PinFriendlyName=%s," % friendly
    if direction == "out":
        s += 'Direction="EGPD_Output",'
    s += 'PinType.PinCategory="%s",PinType.PinSubCategory="%s",PinType.PinSubCategoryObject=%s,' % (
        cat, sub, '"%s"' % obj if obj else "None")
    s += "PinType.PinSubCategoryMemberReference=%s,PinType.PinValueType=(),PinType.ContainerType=%s," % (member_ref, container)
    s += "PinType.bIsReference=%s,PinType.bIsConst=%s,PinType.bIsWeakPointer=False,PinType.bIsUObjectWrapper=False," % (ref, const)
    s += "PinType.bSerializeAsSinglePrecisionFloat=False,"
    if default is not None:
        s += 'DefaultValue="%s",' % str(default).replace('"', '\\"')
    if default_obj is not None:
        s += 'DefaultObject="%s",' % default_obj
    s += "PersistentGuid=00000000000000000000000000000000,bHidden=%s,bNotConnectable=%s,bDefaultValueIsReadOnly=False," % (
        hidden, not_connectable)
    s += "bDefaultValueIsIgnored=False,bAdvancedView=False,bOrphanedPin=False,"
    return {"name": name, "dir": direction, "body": s}


class Node:
    def __init__(self, name, header, pins, footer):
        self.name, self.header, self.pins, self.footer = name, header, pins, footer   # pins: list of dict(name, raw, id)

    def pin(self, pname, direction=None):
        for p in self.pins:
            if p["name"] == pname and (direction is None or p["dir"] == direction):
                return p
        raise KeyError("%s has no pin %r (has %s)" % (self.name, pname, [q["name"] for q in self.pins]))


class Graph:
    def __init__(self, lib_path=LIB_PATH):
        self.lib = json.load(open(lib_path, encoding="utf-8"))["lib"]
        self.nodes = []
        self.counts = {}

    def keys(self, pat=""):
        return sorted(k for k in self.lib if pat.lower() in k.lower())

    def node(self, key, x=0, y=0, header_edits=(), defaults=None, drop_pins=(), pin_edits=None, text=None):
        src = text if text is not None else self.lib[key]["text"]
        lines = src.replace("\r\n", "\n").split("\n")
        m = re.match(r'Begin Object Class=(\S+) Name="([^"]+)"', lines[0])
        cls = m.group(1)
        base = cls.rsplit(".", 1)[1]
        self.counts[base] = self.counts.get(base, 0) + 1
        name = "%s_%d" % (base, 100 + self.counts[base])
        header, pins, footer = ['Begin Object Class=%s Name="%s"' % (cls, name)], [], []
        for ln in lines[1:]:
            pm = PIN_RE.match(ln)
            if pm:
                body = pm.group(2)
                body = re.sub(r"LinkedTo=\([^)]*\),", "", body)
                pid = gid()
                body = re.sub(r"PinId=[0-9A-F]{32}", "PinId=" + pid, body, count=1)
                pname = re.search(r'PinName="([^"]*)"', body).group(1)
                d = "out" if 'Direction="EGPD_Output"' in body else "in"
                if pname in drop_pins:
                    continue
                pins.append({"name": pname, "dir": d, "id": pid, "body": body, "links": [], "indent": pm.group(1)})
            elif ln.strip().startswith("End Object"):
                footer.append(ln)
            elif ln.strip():
                if ln.strip().startswith(("NodePosX=", "NodePosY=", "NodeGuid=", "bCommentBubble", "NodeComment=",
                                          "ErrorType=", "ErrorMsg=", "bHasCompilerMessage=")):
                    continue
                header.append(ln)
        header.append("   NodePosX=%d" % x)
        header.append("   NodePosY=%d" % y)
        header.append("   NodeGuid=%s" % gid())
        hdr = "\n".join(header)
        for a, b in header_edits:
            new = re.sub(a, b, hdr)
            if new == hdr and not re.search(a, hdr):
                raise ValueError("header edit %r matched nothing in %s" % (a, key))
            hdr = new
        node = Node(name, hdr.split("\n"), pins, footer or ["End Object"])
        for pname, val in (defaults or {}).items():
            self.set_default(node, pname, val)
        for pname, edits in (pin_edits or {}).items():
            p = node.pin(pname)
            for a, b in edits:
                p["body"] = re.sub(a, b, p["body"])
        self.nodes.append(node)
        return node

    def raw(self, node_class, header_lines, pins, x=0, y=0):
        """Craft a node from scratch. node_class like '/Script/BlueprintGraph.K2Node_CallFunction';
        pins: list of dicts from mkpin()."""
        base = node_class.rsplit(".", 1)[1]
        self.counts[base] = self.counts.get(base, 0) + 1
        name = "%s_%d" % (base, 100 + self.counts[base])
        header = ['Begin Object Class=%s Name="%s"' % (node_class, name)] + ["   " + h for h in header_lines] + \
                 ["   NodePosX=%d" % x, "   NodePosY=%d" % y, "   NodeGuid=%s" % gid()]
        ps = []
        for p in pins:
            pid = gid()
            ps.append({"name": p["name"], "dir": p["dir"], "id": pid, "body": "PinId=%s,%s" % (pid, p["body"]), "links": [], "indent": "   "})
        n = Node(name, header, ps, ["End Object"])
        self.nodes.append(n)
        return n

    @staticmethod
    def set_default(node, pname, val, obj=False):
        p = node.pin(pname, "in")
        body = re.sub(r'DefaultValue="(?:[^"\\]|\\.)*",', "", p["body"])
        body = re.sub(r"DefaultObject=(?:None|\"[^\"]*\"),", "", body)
        body = re.sub(r"DefaultTextValue=(?:[^,]*\([^)]*\)|[^,]*),", "", body)
        ins = ('DefaultObject="%s",' % val) if obj else ('DefaultValue="%s",' % str(val).replace('"', '\\"'))
        body = body.replace("PinType.PinCategory", ins + "PinType.PinCategory", 1) if "PinType.PinCategory" in body else body + "," + ins
        p["body"] = body

    def link(self, a, apin, b, bpin):
        pa = a.pin(apin, "out")
        pb = b.pin(bpin, "in")
        pa["links"].append("%s %s" % (b.name, pb["id"]))
        pb["links"].append("%s %s" % (a.name, pa["id"]))

    def text(self):
        out = []
        for n in self.nodes:
            out += n.header
            for p in n.pins:
                body = p["body"]
                if p["links"]:
                    lt = "LinkedTo=(%s,)," % ",".join(p["links"])
                    body = body.replace("PersistentGuid=", lt + "PersistentGuid=", 1) if "PersistentGuid=" in body else body + "," + lt
                out.append("%sCustomProperties Pin (%s)" % (p["indent"], body))
            out += n.footer
        return "\n".join(out) + "\n"
